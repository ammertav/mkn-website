/**
 * Mengembalikan objek dosen yang sudah terlokalisasi sesuai bahasa yang aktif ('id' atau 'en').
 * Properti asli dipertahankan, sementara teks deskriptif diterjemahkan secara dinamis.
 */
export function getLocalizedFaculty(faculty, lang = "id") {
  if (!faculty) return faculty;
  const t = facultyTranslations[faculty.slug] || facultyTranslations[String(faculty.id)];
  if (!t) return faculty;

  const currentLang = lang === "en" ? "en" : "id";

  return {
    ...faculty,
    originalTitle: faculty.title,
    originalBio: faculty.bio,
    originalExpertise: faculty.expertise,
    originalType: faculty.type,
    title: t.title?.[currentLang] || faculty.title,
    expertise: t.expertise?.[currentLang] || faculty.expertise,
    type: t.type?.[currentLang] || faculty.type,
    bio: t.bio?.[currentLang] || faculty.bio,
    fullBio: t.fullBio?.[currentLang] || faculty.fullBio,
  };
}
